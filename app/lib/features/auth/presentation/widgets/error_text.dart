import '../../../../core/error/failure.dart';
import '../../../../l10n/app_localizations.dart';

/// Traduce el `code` de la API al idioma de la app (mismo contrato que web/messages → errors).
String errorText(AppLocalizations l10n, Object error) {
  final failure = error is Failure ? error : const Failure('', code: 'UNKNOWN');
  final minutes = ((failure.retryAfterSeconds ?? 60) / 60).ceil().clamp(1, 1440);
  final max = (failure.details['max'] as num?)?.toInt() ?? 0;
  return switch (failure.code) {
    'NETWORK_ERROR' => l10n.errNetwork,
    'SERVER_ERROR' || 'INTERNAL_ERROR' => l10n.errServer,
    'VALIDATION_FAILED' => l10n.errValidation,
    'TOO_MANY_REQUESTS' => l10n.errTooManyRequests,
    'SESSION_INVALID' || 'UNAUTHENTICATED' => l10n.errSessionInvalid,
    'REFRESH_REUSED' => l10n.errRefreshReused,
    'PERMISSION_DENIED' || 'ROLE_NOT_ALLOWED' => l10n.errPermissionDenied,
    'INVALID_PHONE' => l10n.errInvalidPhone,
    'OTP_SEND_LIMIT' => l10n.errOtpSendLimit(minutes),
    'OTP_INVALID' => l10n.errOtpInvalid(failure.remainingAttempts ?? 0),
    'OTP_EXPIRED' => l10n.errOtpExpired,
    'OTP_LOCKED' => l10n.errOtpLocked,
    'OTP_NOT_FOUND' => l10n.errOtpNotFound,
    'OTP_PROVIDER_UNAVAILABLE' => l10n.errOtpProviderUnavailable,
    'INVALID_CREDENTIALS' => l10n.errInvalidCredentials,
    'PASSWORD_LOCKED' => l10n.errPasswordLocked(minutes),
    'WEAK_PASSWORD' => l10n.errWeakPassword,
    'ACCOUNT_DISABLED' => l10n.errAccountDisabled,
    'REGISTRATION_EXPIRED' => l10n.errRegistrationExpired,
    'CONSENT_REQUIRED' => l10n.errConsentRequired,
    'PHONE_ALREADY_REGISTERED' => l10n.errPhoneAlreadyRegistered,
    'ROLE_NOT_GRANTED' => l10n.errRoleNotGranted,
    'PASSWORD_REQUIRED' => l10n.errPasswordRequired,
    'SAME_PHONE' => l10n.errSamePhone,
    'PASSWORD_NOT_SET' => l10n.errPasswordNotSet,
    'ESTABLISHMENT_NOT_FOUND' => l10n.errEstablishmentNotFound,
    'EMPTY_ORDER' => l10n.errEmptyOrder,
    'TOO_MANY_LINES' => l10n.errTooManyLines(max),
    'INVALID_QUANTITY' => l10n.errInvalidQuantity(max),
    'DUPLICATE_PRODUCT' => l10n.errDuplicateProduct,
    'PRODUCTS_UNAVAILABLE' => l10n.errProductsUnavailable,
    'PRODUCTS_CHANGED' => l10n.errProductsChanged,
    'ESTABLISHMENT_NOT_ACCEPTING_ORDERS' => l10n.errEstablishmentNotAcceptingOrders,
    'NEW_CUSTOMER_LIMIT' => l10n.errNewCustomerLimit,
    'PAYMENT_METHOD_UNAVAILABLE' => l10n.errPaymentMethodUnavailable,
    'ORDERS_NOT_CONFIGURED' => l10n.errOrdersNotConfigured,
    'ADDRESS_NOT_FOUND' => l10n.errAddressNotFound,
    'RECIPIENT_NOT_FOUND' => l10n.errRecipientNotFound,
    'TOO_MANY_ADDRESSES' => l10n.errTooManyAddresses(max),
    'ORDER_NOT_FOUND' => l10n.errOrderNotFound,
    'REQUEST_REUSED' => l10n.errRequestReused,
    'NO_COVERAGE' => l10n.errNoCoverage,
    'OUTSIDE_OPERATING_HOURS' => l10n.errOutsideOperatingHours,
    'TEXT_REQUIRED' => l10n.errTextRequired(failure.details['field']?.toString() ?? 'other'),
    'TRIP_NOT_FOUND' => l10n.errTripNotFound,
    'TRIP_STEP_NOT_ALLOWED' => l10n.errTripStepNotAllowed,
    'PURCHASE_AMOUNT_INVALID' => l10n.errPurchaseAmountInvalid,
    'RECEIPT_INVALID' => l10n.errReceiptInvalid,
    'DELIVERY_CODE_WRONG' => l10n.errDeliveryCodeWrong((failure.details['attemptsLeft'] as num?)?.toInt() ?? 0),
    'DELIVERY_CODE_LOCKED' => l10n.errDeliveryCodeLocked,
    'DELIVERY_PROOF_TOO_EARLY' => l10n.errDeliveryProofTooEarly,
    'DELIVERY_PROOF_INVALID' => l10n.errDeliveryProofInvalid,
    'DELIVERY_STEP_NOT_ALLOWED' => l10n.errDeliveryStepNotAllowed,
    'CLIENT_EVENT_CONFLICT' => l10n.errClientEventConflict,
    'ADJUSTMENT_CLOSED' => l10n.errAdjustmentClosed,
    'ADJUSTMENT_OPTION_INVALID' => l10n.errAdjustmentOptionInvalid,
    'SUBSTITUTE_UNAVAILABLE' => l10n.errSubstituteUnavailable,
    'ADJUSTMENT_REPORT_INVALID' => failure.details['problem'] == 'PRICE_UNCHANGED' ? l10n.tripReportPriceSame : l10n.errAdjustmentReportInvalid,
    'ADJUSTMENT_LINES_INVALID' => l10n.errAdjustmentLinesInvalid,
    'COLLECTION_INVALID' => switch (failure.details['problem']) {
        'NO_ACCOUNT' => l10n.errCollectionNoAccount,
        'REPEATED_METHOD' => l10n.collectRepeated,
        _ => l10n.errCollectionInvalid,
      },
    'COLLECTION_ORDER_NOT_FOUND' => l10n.errCollectionOrderNotFound,
    'COLLECTION_STEP_NOT_ALLOWED' => l10n.errCollectionStepNotAllowed,
    'COLLECTION_ACCOUNT_NOT_FOUND' => l10n.errCollectionAccountNotFound,
    'COURIER_HAS_ACTIVE_ORDER' => l10n.errCourierHasActiveOrder,
    'ORDER_ALREADY_TAKEN' => l10n.errOrderAlreadyTaken,
    'OFFER_EXPIRED' => l10n.errOfferExpired,
    'OFFER_CLOSED' || 'OFFER_NOT_FOUND' => l10n.errOfferClosed,
    'COURIER_BUSY' => l10n.errCourierBusy,
    'COURIER_NOT_AVAILABLE' => l10n.errCourierNotAvailable,
    'COURIER_NOT_VERIFIED' => l10n.errCourierNotVerified,
    'COURIER_MUNICIPALITY_NOT_OPERATING' => l10n.errCourierMunicipalityNotOperating,
    'LOCATION_CONSENT_REQUIRED' => l10n.errLocationConsentRequired,
    'LOCATION_NOT_EXPECTED' => l10n.errLocationNotExpected,
    'FILE_CONTENT_MISMATCH' || 'FILE_INVALID_CHECKSUM' || 'FILE_NOT_UPLOADED' || 'FILE_TOO_LARGE' || 'FILE_TYPE_NOT_ALLOWED' || 'UPLOAD_EXPIRED' || 'UPLOAD_INVALID' =>
      l10n.errFileUpload,
    _ => l10n.errUnknown,
  };
}

/// Códigos tras los que el código enviado ya no sirve: hay que pedir otro.
bool isDeadCode(Object error) =>
    error is Failure && const {'OTP_EXPIRED', 'OTP_LOCKED', 'OTP_NOT_FOUND'}.contains(error.code);
